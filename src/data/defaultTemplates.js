// --- Custom Editor authoring helpers (legacy heading/blocks shape — --------
// --- normalizeSchema() in templateBuilder.js upgrades it on load) ----------

function img(slug, alt) {
  return { type: 'image', url: `{{PLACEHOLDER_BASE}}/${slug}.png`, alt };
}

function p(text) {
  return { type: 'paragraph', text };
}

function btn(label, urlVar = 'subscribe_url') {
  return { type: 'button', label, url: `{{${urlVar}}}` };
}

// `{{company}}` is real campaign merge data (recipient.merge_data.company) —
// it resolves safely blank if a contact has none set. Mobile numbers / custom
// links / social links are intentionally left empty here: a generic default
// template cannot know any one business's own phone number, policy links, or
// social profiles — the client adds their own via the Design tab's footer
// section (same "add your own" spirit as the placeholder images).
const STANDARD_FOOTER = {
  footerTexts: ['{{company}}'],
  mobileNumbers: [],
  customLinks: [],
  socialLinks: [],
  unsubscribeText: 'Unsubscribe from these emails',
};

// --- Drag & Drop Builder authoring helpers (block-tree shape) --------------

const TEXT_STYLE = 'margin:0 0 16px;font-size:15px;line-height:1.7;color:#374151';
const TEXT_STYLE_CENTER = 'margin:0 0 16px;font-size:15px;line-height:1.7;color:#374151;text-align:center';
const TEXT_STYLE_LIGHT_CENTER = 'margin:0 0 16px;font-size:15px;line-height:1.7;color:#ffffff;text-align:center';
const TEXT_STYLE_SMALL = 'margin:0;font-size:13px;line-height:1.6;color:#4b5563;text-align:center';

function bText(html, style = TEXT_STYLE) {
  return { type: 'text', html: `<p style="${style}">${html}</p>` };
}

function bHeading(text, opts = {}) {
  return {
    type: 'heading',
    text,
    level: opts.level || 'h1',
    align: opts.align || 'left',
    color: opts.color || '#111827',
    fontSize: opts.fontSize || 22,
  };
}

function bImage(slug, alt, opts = {}) {
  return { type: 'image', url: `{{PLACEHOLDER_BASE}}/${slug}.png`, alt, width: opts.width || 536, align: opts.align || 'center', link: '' };
}

function bButton(label, opts = {}) {
  return {
    type: 'button',
    label,
    url: '{{subscribe_url}}',
    align: opts.align || 'left',
    bgColor: opts.bgColor || '#4f46e5',
    textColor: '#ffffff',
    fontSize: 15,
  };
}

function bDivider() {
  return { type: 'divider', color: '#e5e7eb', thickness: 1 };
}

function bFooterText() {
  return { type: 'footerText', text: '{{company}}' };
}

function bUnsubscribe() {
  return { type: 'unsubscribe', label: 'Unsubscribe from these emails' };
}

function bRow(columnBlocks, opts = {}) {
  const widths = opts.widths || (columnBlocks.length === 2 ? [50, 50] : columnBlocks.length === 3 ? [34, 33, 33] : [100]);
  return {
    backgroundColor: opts.backgroundColor || '#ffffff',
    padding: opts.padding || { top: 24, right: 24, bottom: 24, left: 24 },
    columns: columnBlocks.map((blocks, i) => ({ widthPct: widths[i], blocks })),
  };
}

function footerRow() {
  return bRow([[bDivider(), bFooterText(), bUnsubscribe()]], { backgroundColor: '#f9fafb' });
}

function builderSchema(rows, backgroundColor = '#f4f5fa') {
  return { version: 1, globalStyle: { backgroundColor, contentWidth: 600, fontFamily: EMAIL_SAFE_FONT }, rows };
}

