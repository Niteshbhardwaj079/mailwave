// ---------------------------------------------------------------------------
// The 22 built-in default (master) templates — 6 Custom Editor, 6 HTML
// Upload, 10 Drag & Drop Builder (source: 'custom' | 'html_upload' |
// 'builder'). Seeded once (server/src/db/seed.js), marked is_default:true.
//
// Default templates ARE editable in place (Save updates the same row,
// permanently — see server/src/routes/templates.js PUT handler) — only
// DELETE stays blocked, at both the UI and the API. Real, purpose-written
// copy per template, not lorem ipsum, and every one of the 22 is
// structurally distinct (header/hero shape, column layout, CTA placement,
// section order) — not a palette/copy swap of a shared layout.
//
// Placeholder images: every `{{PLACEHOLDER_BASE}}` token below is resolved by
// resolveDefaultTemplateSchema()/renderDefaultTemplateHtml() into `<publicUrl>
// /template-placeholders/<slug>.png` — real PNG files committed to
// server/public/template-placeholders/, generated by
// server/.scratch/generate_placeholders.mjs. Deliberately not an external
// placeholder service or an inline SVG/data-URI: those are stripped or render
// unreliably in Gmail/Outlook/Apple Mail, and an external service can go
// offline. A real, app-hosted PNG never can. Several templates deliberately
// carry no image at all — genuine typography/color-driven layouts, both for
// visual variety and to keep file size down.
// ---------------------------------------------------------------------------
