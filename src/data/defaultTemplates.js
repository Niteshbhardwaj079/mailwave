/** Placeholder tokens ko is deployment ke asli, app-hosted PNG URL se badalta hai. HTML Upload entries ke paas koi schema nahi hota (content_schema null). */
export function resolveDefaultTemplateSchema(entry, placeholderBaseUrl) {
  if (entry.source === 'html_upload' || !entry.schema) return null;
  const json = JSON.stringify(entry.schema).replace(/\{\{PLACEHOLDER_BASE\}\}/g, placeholderBaseUrl);
  return JSON.parse(json);
}

/**
 * `source` ke hisaab se sahi compiler chunta hai:
 *   - custom       -> renderTemplateHtml(schema, {tokenize:true}) (Design tab
 *                      ka har field apna {{key}} token save karta hai)
 *   - builder      -> compileBuilderHtml(schema) (block-tree se seedha compile,
 *                      koi tokenize concept nahi — TemplateBuilderPage jaisa hi)
 *   - html_upload  -> raw HTML, jaisa-ka-taisa (bas {{PLACEHOLDER_BASE}} resolve)
 */
export function renderDefaultTemplateHtml(entry, placeholderBaseUrl) {
  if (entry.source === 'html_upload') {
    return entry.html.replaceAll('{{PLACEHOLDER_BASE}}', placeholderBaseUrl);
  }
  const schema = resolveDefaultTemplateSchema(entry, placeholderBaseUrl);
  if (entry.source === 'builder') {
    return compileBuilderHtml(schema);
  }
  return renderTemplateHtml(schema, { tokenize: true });
}
